"""
visualize_dataset.py

Visualize datasets generated by CPG/ESN experiments for soft tentacle robots.
- Static plots: joint angles, end-effector trajectory, reward over time
- Animation: tentacle motion (matplotlib, exportable as GIF/MP4)
"""
import numpy as np
import matplotlib.pyplot as plt
import matplotlib.animation as animation
import argparse
import matplotlib
matplotlib.use('Agg')  # Use non-GUI backend for file output

# --- Helper for forward kinematics of a planar tentacle ---
def tentacle_forward_kinematics(joint_angles, seg_length=0.05):
    """Compute (x, y) positions of each segment end for a planar tentacle."""
    x, y, theta = 0.0, 0.0, 0.0
    xs, ys = [x], [y]
    for angle in joint_angles:
        theta += angle
        x += seg_length * np.cos(theta)
        y += seg_length * np.sin(theta)
        xs.append(x)
        ys.append(y)
    return np.array(xs), np.array(ys)

# --- Static plots ---
def plot_joint_angles(X, ep_lens, n_joints=16, save_path=None):
    plt.figure(figsize=(10, 6))
    t = np.arange(X.shape[0])
    for j in range(n_joints):
        plt.plot(t, X[:, j], label=f'Joint {j}')
    plt.xlabel('Timestep')
    plt.ylabel('Joint Angle (rad)')
    plt.title('Joint Angles Over Time')
    plt.legend(ncol=2, fontsize=8)
    plt.tight_layout()
    if save_path:
        plt.savefig(save_path)
    else:
        plt.show()
    plt.close()

def plot_end_effector_trajectory(X, n_joints=16, save_path=None):
    traj = [tentacle_forward_kinematics(X[i, :n_joints]) for i in range(X.shape[0])]
    xs = [x[-1] for x, y in traj]
    ys = [y[-1] for x, y in traj]
    plt.figure(figsize=(6, 6))
    plt.plot(xs, ys, marker='o', markersize=2, linewidth=1)
    plt.xlabel('X (m)')
    plt.ylabel('Y (m)')
    plt.title('End-Effector Trajectory')
    plt.axis('equal')
    plt.tight_layout()
    if save_path:
        plt.savefig(save_path)
    else:
        plt.show()
    plt.close()

# --- Animation ---
def animate_tentacle(X, n_joints=16, seg_length=0.05, out_gif=None):
    fig, ax = plt.subplots(figsize=(6, 6))
    ax.set_xlim(-n_joints*seg_length, n_joints*seg_length)
    ax.set_ylim(-n_joints*seg_length, n_joints*seg_length)
    ax.set_xlabel('X (m)')
    ax.set_ylabel('Y (m)')
    ax.set_title('Tentacle Motion Animation')
    line, = ax.plot([], [], 'o-', lw=2)

    def init():
        line.set_data([], [])
        return (line,)

    def update(frame):
        xs, ys = tentacle_forward_kinematics(X[frame, :n_joints], seg_length)
        line.set_data(xs, ys)
        return (line,)

    ani = animation.FuncAnimation(fig, update, frames=X.shape[0], init_func=init, blit=True, interval=30)
    if out_gif:
        ani.save(out_gif, writer='pillow', fps=30)
    plt.show()

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument('dataset', type=str, help='Path to .npz dataset file')
    parser.add_argument('--plot-joints', action='store_true', help='Plot joint angles over time')
    parser.add_argument('--plot-trajectory', action='store_true', help='Plot end-effector trajectory')
    parser.add_argument('--animate', action='store_true', help='Show tentacle animation')
    parser.add_argument('--save-gif', type=str, default=None, help='Save animation as GIF to this path')
    parser.add_argument('--save-plot', type=str, default=None, help='Save static plot to this path (PNG, PDF, etc.)')
    parser.add_argument('--n-joints', type=int, default=16, help='Number of joints (channels) in tentacle')
    args = parser.parse_args()

    data = np.load(args.dataset, allow_pickle=True)
    X = data['X']
    ep_lens = data.get('ep_lens', None)
    n_joints = args.n_joints

    if args.plot_joints:
        plot_joint_angles(X, ep_lens, n_joints=n_joints, save_path=args.save_plot)
    if args.plot_trajectory:
        plot_end_effector_trajectory(X, n_joints=n_joints, save_path=args.save_plot)
    if args.animate:
        animate_tentacle(X, n_joints=n_joints, out_gif=args.save_gif)
